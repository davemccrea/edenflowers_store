defmodule Edenflowers.Pricing.Promotion do
  @moduledoc """
  A discount code with validity dates, optional usage limit, and minimum cart total. Newsletter signup creates a one-use promotion.
  Its `kind` says what it was made for.
  """

  use Ash.Resource,
    domain: Edenflowers.Pricing,
    data_layer: AshPostgres.DataLayer,
    authorizers: [Ash.Policy.Authorizer],
    notifiers: [Ash.Notifier.PubSub],
    extensions: [AshPaperTrail.Resource]

  alias Edenflowers.Accounts.Calculations.NamePart
  alias Edenflowers.Events
  alias Edenflowers.Orders.Validations.Holds
  alias Edenflowers.Pricing.Changes

  postgres do
    table "promotions"
    repo Edenflowers.Repo
    migration_types minimum_cart_total: :decimal

    references do
      reference :gift_order, on_delete: :nilify
    end

    check_constraints do
      check_constraint :minimum_cart_total, "promotions_valid_minimum_cart_total",
        check: "minimum_cart_total >= 0 AND minimum_cart_total = round(minimum_cart_total, 2)",
        message: "must be a non-negative amount in whole cents"
    end
  end

  # Mostly so a code that was regenerated by accident can be recovered.
  paper_trail do
    # Records "from → to", so the old code is kept even for promotions
    # created before the trail existed.
    change_tracking_mode :full_diff
    # Unused promotions can be deleted; their versions stay behind.
    reference_source? false
    store_action_name? true
    # One per subscriber, never edited by hand.
    ignore_actions [:create_for_newsletter, :start_validity]
  end

  actions do
    defaults [
      :read,
      :destroy,
      create: [:name, :code, :discount_rate, :minimum_cart_total, :start_date, :expiration_date, :usage_limit]
    ]

    update :update do
      primary? true
      accept [:name, :code, :discount_rate, :minimum_cart_total, :start_date, :expiration_date, :usage_limit]
      # full_diff can't run atomically.
      require_atomic? false
    end

    update :start_validity do
      description "Starts a pass-it-on code's 30 days: the first time a customer opens its 'Pass it on' page or " <>
                    "applies it, it gets an expiration date 30 days from `today`. Does nothing for other codes, " <>
                    "once the 30 days have started, or when an admin is the actor (Jennie scanning a card)."

      argument :today, :date do
        allow_nil? false
        default &Edenflowers.ShopTime.today/0
        description "The day the 30 days count from. Defaults to today in Helsinki."
      end

      change fn changeset, context ->
        if match?(%{admin: true}, context.actor) do
          changeset
        else
          Ash.Changeset.atomic_update(
            changeset,
            :expiration_date,
            expr(
              if kind == :pass_it_on and is_nil(expiration_date) do
                date_add(^arg(:today), 30, :day)
              else
                expiration_date
              end
            )
          )
        end
      end

      require_atomic? false
    end

    update :link_gift_order do
      description "Jennie links a pass-it-on card to the gift order it goes out with, typing the card's code on " <>
                    "the order's page. A nil `gift_order_id` unlinks it. Either only before handover and before " <>
                    "the recipient opens the card (`gift_order_linkable?`). One card per order, and one order per card: a card " <>
                    "already linked is unlinked before it can go with another order."

      accept [:gift_order_id]

      validate {Holds,
                calculation: :gift_order_linkable?,
                message: "has already been opened, or its gift has been fulfilled or cancelled"}

      # Refuse direct reassignment: a mistyped code must not move another gift's card onto this order.
      validate fn changeset, _context ->
        if is_nil(changeset.data.gift_order_id) or is_nil(Ash.Changeset.get_attribute(changeset, :gift_order_id)) do
          :ok
        else
          {:error,
           Ash.Error.Changes.InvalidAttribute.exception(
             field: :gift_order_id,
             message: "already went with another order"
           )}
        end
      end

      # full_diff can't run atomically.
      require_atomic? false
    end

    update :mark_not_opened do
      description "Jennie puts back a pass-it-on card that was opened by mistake, such as her own test scan while " <>
                    "logged out. Its expiration date is cleared, so its 30 days start again at the next customer " <>
                    "scan and it can be linked to a gift again. Only for an opened or expired card that hasn't " <>
                    "been used (`card_resettable?`)."

      validate {Holds, calculation: :card_resettable?, message: "hasn't been opened, or has already been used"}

      change set_attribute(:expiration_date, nil)

      # full_diff can't run atomically.
      require_atomic? false
    end

    read :pass_it_on_card_by_code do
      description "A pass-it-on card by the code printed on it, whether or not its code is still usable."

      argument :code, :ci_string, allow_nil?: false
      get? true

      filter expr(kind == :pass_it_on and code == ^arg(:code))
    end

    read :by_code do
      description "A promotion by its code, found only while usable: within its dates and under its usage limit."

      argument :code, :string, allow_nil?: false

      argument :today, :date do
        default fn -> Edenflowers.ShopTime.today() end
        description "The day its dates are checked against. Defaults to today in Helsinki."
      end

      filter expr(code == ^arg(:code) and usable?(today: ^arg(:today)))
    end

    read :search_by_code do
      description "Admin search for promotions of every kind by part of their code, any case."

      argument :term, :ci_string, allow_nil?: false

      filter expr(contains(code, ^arg(:term)))

      prepare Edenflowers.Preparations.RankByMatch
      prepare build(sort: [code: :asc], load: [:status, :usage])
    end

    create :create_for_newsletter do
      description "Generates a new newsletter subscriber's welcome code at the `WelcomeOffer` rate: one use, " <>
                    "valid for 30 days."

      change Changes.SetNewsletterDefaults
    end

    create :create_pass_it_on do
      description "One pass-it-on card's code: 15% off one order, any cart total, with a generated code. " <>
                    "`name` is the print batch it belongs to, e.g. 'Skicka vidare 2026-11'."

      accept [:name]

      change set_attribute(:kind, :pass_it_on)
      change set_attribute(:code, &__MODULE__.generate_code/0)
      change set_attribute(:discount_rate, Decimal.new("0.15"))
      change set_attribute(:minimum_cart_total, Decimal.new("0"))
      change set_attribute(:usage_limit, 1)
    end

    action :create_pass_it_on_batch, {:array, :string} do
      description "Creates `count` pass-it-on codes under one batch `name` and returns them, for printing on " <>
                    "cards. All or none: if one code fails (a rare clash with an existing code), none are kept " <>
                    "and the batch can simply be run again."

      argument :name, :string, allow_nil?: false
      argument :count, :integer, allow_nil?: false, constraints: [min: 1]

      run fn input, context ->
        %{name: name, count: count} = input.arguments

        result =
          Ash.bulk_create(List.duplicate(%{name: name}, count), __MODULE__, :create_pass_it_on,
            actor: context.actor,
            return_records?: true,
            return_errors?: true,
            stop_on_error?: true,
            transaction: :all
          )

        case result do
          %Ash.BulkResult{status: :success, records: records} -> {:ok, Enum.map(records, &to_string(&1.code))}
          %Ash.BulkResult{errors: errors} -> {:error, errors}
        end
      end
    end
  end

  policies do
    # System bypass is scoped to the actions our jobs/webhooks actually invoke.
    bypass actor_attribute_equals(:system, true) do
      authorize_if action(:create_for_newsletter)
      # A print batch is made over rpc on production.
      authorize_if action([:create_pass_it_on_batch, :create_pass_it_on])
      authorize_if action_type(:read)
    end

    bypass actor_attribute_equals(:admin, true) do
      authorize_if always()
    end

    # Any visitor opening a card's page or applying its code starts its 30 days.
    bypass action(:start_validity) do
      authorize_if always()
    end

    policy action_type(:read) do
      authorize_if always()
    end

    policy action_type([:create, :update, :destroy]) do
      description "All mutations require admin actor (covered by bypass above)."
      forbid_if always()
    end
  end

  pub_sub do
    module EdenflowersWeb.Endpoint

    publish_all :create, Events.admin_promotions()
    publish_all :update, Events.admin_promotions()
    publish_all :destroy, Events.admin_promotions()

    publish_all :update, Events.admin_promotion(:id)
    publish_all :destroy, Events.admin_promotion(:id)

    publish_all :create, Events.admin_pass_it_on(), filter: &pass_it_on?/1
    publish_all :update, Events.admin_pass_it_on(), filter: &pass_it_on?/1
    publish_all :destroy, Events.admin_pass_it_on(), filter: &pass_it_on?/1
  end

  defp pass_it_on?(%{data: %{kind: :pass_it_on}}), do: true
  defp pass_it_on?(_notification), do: false

  attributes do
    uuid_primary_key :id
    attribute :name, :string, allow_nil?: false

    attribute :kind, :atom do
      description "What the code was made for, fixed at creation: `manual` for codes Jennie makes, `pass_it_on` " <>
                    "for a card batch, `newsletter` for a subscriber's welcome code. Never edited."

      allow_nil? false
      default :manual
      constraints one_of: [:manual, :pass_it_on, :newsletter]
    end

    attribute :code, :ci_string do
      allow_nil? false
      constraints allow_empty?: false, trim?: true
    end

    attribute :discount_rate, :decimal do
      description "The discount as a fraction, so 0.1 is 10% off."
      allow_nil? false
      constraints greater_than: 0, max: 1
    end

    attribute :minimum_cart_total, :decimal do
      description "In euros, VAT included."
      allow_nil? false
      constraints min: 0, scale: 2
    end

    attribute :start_date, :date
    attribute :expiration_date, :date
    attribute :usage_limit, :integer, constraints: [min: 1]
  end

  relationships do
    has_many :orders, Edenflowers.Orders.Order do
      description "Orders the code was applied to, carts included. See `usage` for the ones that count."
    end

    has_many :placed_orders, Edenflowers.Orders.Order do
      description "Placed orders the code was used on, leaving out cancelled ones, as `usage` does."
      filter expr(state == :placed and fulfillment_status != :cancelled)
      sort ordered_at: :asc, id: :asc
    end

    belongs_to :gift_order, Edenflowers.Orders.Order do
      description "For a pass-it-on card: the gift delivery Jennie sent it out with. Nil for a card she didn't " <>
                    "link, and for other codes."
    end

    has_one :newsletter_subscriber, Edenflowers.Accounts.User do
      description "The subscriber this welcome code was generated for. Nil for codes Jennie made herself."
      destination_attribute :newsletter_promo_id
    end
  end

  calculations do
    calculate :match_rank, :integer, expr(match_rank(code, ^arg(:term))) do
      description "How closely the admin search term matches what a result row shows (see `match_rank`): " <>
                    "0 exact, 1 at the start of a word, 2 elsewhere, 3 for a match in a field the row " <>
                    "doesn't show. The search sorts by it."

      argument :term, :ci_string, allow_nil?: false
    end

    calculate :matches?,
              :boolean,
              expr(contains(name, ^arg(:term)) or contains(code, ^arg(:term))) do
      description "The admin promotions search, case-insensitive: whether the term appears in the name or code."
      argument :term, :ci_string, allow_nil?: false
    end

    calculate :status,
              :atom,
              expr(
                cond do
                  not is_nil(start_date) and ^arg(:today) < start_date -> :scheduled
                  not is_nil(expiration_date) and ^arg(:today) > expiration_date -> :expired
                  not is_nil(usage_limit) and usage >= usage_limit -> :used_up
                  true -> :active
                end
              ) do
      description "Where the promotion stands on `today`: `scheduled` before its start date, `expired` after its " <>
                    "expiry date (both inclusive Helsinki days), `used_up` once its usage reaches its limit, and " <>
                    "otherwise `active`. Only an active one can be applied (`usable?`)."

      argument :today, :date, allow_nil?: false, default: &Edenflowers.ShopTime.today/0
      constraints one_of: [:scheduled, :expired, :used_up, :active]
    end

    calculate :usable?, :boolean, expr(status(today: ^arg(:today)) == :active) do
      description "Can be applied on `today`: its `status` is `active`, so within its dates and under its usage limit."

      argument :today, :date, allow_nil?: false, default: &Edenflowers.ShopTime.today/0
    end

    calculate :gift_order_linkable?,
              :boolean,
              expr(
                kind == :pass_it_on and is_nil(expiration_date) and
                  (is_nil(gift_order_id) or exists(gift_order, pass_it_on_card_changeable?))
              ) do
      description "A pass-it-on card Jennie can still link to its gift delivery: its recipient hasn't opened it " <>
                    "yet, which would have started its 30 days, and any linked gift is still to deliver."
    end

    calculate :card_status,
              :atom,
              expr(
                cond do
                  usage > 0 -> :used
                  not is_nil(expiration_date) and ^arg(:today) > expiration_date -> :expired
                  not is_nil(expiration_date) -> :opened
                  true -> :not_opened
                end
              ) do
      description "Where a pass-it-on card is, for admin: `not_opened` until its recipient first opens its page " <>
                    "or applies its code, `opened` once its 30 days run, `used` once an order placed with it " <>
                    "counts, or `expired` when its inclusive validity date has passed without a live redemption."

      argument :today, :date, allow_nil?: false, default: &Edenflowers.ShopTime.today/0
      constraints one_of: [:not_opened, :opened, :used, :expired]
    end

    calculate :card_resettable?, :boolean, expr(kind == :pass_it_on and not is_nil(expiration_date) and usage == 0) do
      description "A pass-it-on card Jennie can mark as not opened again: its 30 days have started (it is " <>
                    "`opened` or `expired`) and no order placed with it counts."
    end

    calculate :recipient_first_name, :string, {NamePart, source: :gift_recipient_name, part: :first} do
      description "The first name the card's page greets its recipient by. Nil for a card not linked to a gift."
    end
  end

  aggregates do
    # Read the recipient name without order authorization so the card page can greet a guest.
    first :gift_recipient_name, :gift_order, :recipient_name do
      description "The full name of the recipient of the gift the card came with. Only its first name is shown."
      authorize? false
    end

    # Count usage without order authorization so guests cannot bypass the limit by seeing only their own orders.
    count :usage, :orders do
      description "How many placed orders used the code, leaving out cancelled ones. Counted against `usage_limit`."
      filter expr(state == :placed and fulfillment_status != :cancelled)
      authorize? false
    end
  end

  identities do
    identity :unique_code, [:code]
    identity :one_card_per_gift_order, [:gift_order_id], message: "already has a card"
  end

  def generate_code, do: :crypto.strong_rand_bytes(3) |> Base.encode16()
end
